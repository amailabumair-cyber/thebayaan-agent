    def _normalize_ur(self, text: str) -> str:
        """اردو متن سے اعراب ہٹاتا ہے اور حروف کو ہم آہنگ کرتا ہے تاکہ تلاش درست ہو"""
        if not text:
            return ""
        t = text.strip().lower()
        replacements = {
            "ي": "ی", "ى": "ی", "ئ": "ی", "ك": "ک", "ة": "ہ", "ۂ": "ہ",
            "أ": "ا", "إ": "ا", "آ": "ا", "ؤ": "و",
            "َ": "", "ِ": "", "ُ": "", "ً": "", "ٍ": "", "ٌ": "", "ّ": "", "ْ": "", "ٰ": ""
        }
        for k, v in replacements.items():
            t = t.replace(k, v)
        return t

