def normalize_ur(text: str) -> str:
    """اردو اور عربی متن سے اعراب ہٹاتا ہے اور حروف کو یکساں کرتا ہے"""
    if not text:
        return ""
    t = text.strip().lower()
    replacements = {
        "ي": "ی", "ى": "ی", "ئ": "ی", "ك": "ک", "ة": "ہ", "ۂ": "ہ",
        "أ": "ا", "إ": "ا", "آ": "ا", "ؤ": "و",
        "َ": "", "ِ": "", "ُ": "", "ً": "", "ٍ": "", "ٌ": "", "ّ": "", "ْ": "", "ٰ": ""
    }
    for k, v in replacements.items():
        t = t.replace(k, v)
    return t

def compute_hash(question: str, options: List[str] = None) -> str:
    normalized = question.strip().lower()
    if options:
        normalized += "_" + "_".join(sorted([opt.strip().lower() for opt in options]))
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()

