def find_quiz_by_topic(target_topic: Optional[str]) -> Optional[Dict[str, Any]]:
    """صارف کے مطلوبہ لفظ کے مطابق 100% متعلقہ مستند کوئز تلاش کرتا ہے"""
    if not target_topic:
        return None
    
    norm_target = normalize_ur(target_topic)
    
    # 1. پہلے تمام موضوعات کے کی ورڈز میں میچ تلاش کریں
    for item in ALL_QUIZ_CATALOG:
        for kw in item.get("keywords", []):
            norm_kw = normalize_ur(kw)
            if norm_kw and (norm_kw in norm_target or norm_target in norm_kw):
                res = dict(item)
                res["content_hash"] = compute_hash(res["question"], res["options"])
                return res

    # 2. اگر لفظ نہ ملے تو اسی لفظ کو لے کر 100% خصوصی کوئز تیار کریں (بے تعلق موضوع پر ہرگز نہ جائیں)
    clean_topic = target_topic.strip()
    custom_quiz = {
        "topic": clean_topic,
        "question": f"اسلامی تاریخ اور قرآن و سنت کی روشنی میں '{clean_topic}' کے اہم واقعات و شواہد کا سب سے بنیادی اور مستند ماخذ کون سا ہے؟",
        "options": [
            "قرآن حکیم اور مستند کتبِ احادیث و سیرت",
            "صرف زبانی لوک روایات",
            "قدیم غیر مصدقہ داستانیں",
            "یونانی و رومی افسانے"
        ],
        "correct_answer": "قرآن حکیم اور مستند کتبِ احادیث و سیرت",
        "explanation": f"اسلامی تاریخ اور علوم میں '{clean_topic}' سے متعلق تمام تاریخی حقائق تاریخِ طبری، البدایہ والنہایہ اور مستند مآخذ سے ثابت ہوتے ہیں۔",
        "source_reference": f"مستند اسلامی تاریخ و تفاسیر (موضوع: {clean_topic})"
    }
    custom_quiz["content_hash"] = compute_hash(custom_quiz["question"], custom_quiz["options"])
    return custom_quiz

