class CalendarGenerator:
    """
    30 روزہ متوازن کیلنڈر تیار کرتا ہے اور ڈیٹا بیس میں درج کرتا ہے۔
    """

    async def generate_and_save_calendar(self, start_date: Optional[str] = None) -> int:
        """
        30 دن کا کیلنڈر تیار کر کے DB میں محفوظ کرے۔
        """
        if not start_date:
            now_pkt = datetime.now(PKT)
            start_dt = now_pkt + timedelta(days=1)  # کل سے شروع
        else:
            start_dt = datetime.strptime(start_date, "%Y-%m-%d")

        saved_count = 0

        async with AsyncSessionLocal() as session:
            # پچھلی اندراجات کو صاف کر کے نیا 30 روزہ شیڈول تیار کریں
            await session.execute(delete(ContentCalendarEntry))

            for item in CALENDAR_30_DAYS_BLUEPRINT:
                day_offset = item["day"] - 1
                target_date_str = (start_dt + timedelta(days=day_offset)).strftime("%Y-%m-%d")

                entry = ContentCalendarEntry(
                    day_number=item["day"],
                    target_date=target_date_str,
                    category=item["category"],
                    video_title_urdu=item["video_title"],
                    quiz_proposal_urdu=item["quiz"],
                    poll_proposal_urdu=item["poll"],
                    production_priority=item["priority"],
                    notes_urdu=item["notes"],
                )
                session.add(entry)
                saved_count += 1

            await session.commit()

        logger.info(f"{saved_count} روزہ کونٹینٹ کیلنڈر ڈیٹا بیس میں محفوظ ہوا")
        return saved_count

    async def get_calendar_entries(self) -> List[ContentCalendarEntry]:
        """تمام کیلنڈر اینٹریز ترتیب وار واپس کرے"""
        async with AsyncSessionLocal() as session:
            stmt = select(ContentCalendarEntry).order_by(ContentCalendarEntry.day_number.asc())
            return list((await session.execute(stmt)).scalars().all())


# Singleton
calendar_generator = CalendarGenerator()
