class TopicGenerator:
    """
    موضوعات کی تجاویز تیار کرتا ہے، ان کے فنگر پرنٹس نکالتا ہے اور ڈیٹا بیس میں محفوظ کرتا ہے۔
    """

    async def seed_curated_proposals(self) -> int:
        """
        بنیادی مستند تاریخی موضوعات کو ڈیٹا بیس میں درج کرے (ڈپلیکیٹ چھوڑ کر)۔
        """
        saved = 0
        async with AsyncSessionLocal() as session:
            for item in CURATED_TOPICS:
                fp = compute_content_fingerprint(item["topic"])

                # چیک کریں کیا یہ پہلے سے موجود ہے
                stmt = select(ContentTopicProposal).where(
                    ContentTopicProposal.content_fingerprint == fp
                )
                existing = (await session.execute(stmt)).scalars().first()
                if existing:
                    continue

                proposal = ContentTopicProposal(
                    category=item["category"],
                    topic_title_urdu=item["topic"],
                    suggested_titles_json=json.dumps(item["titles"], ensure_ascii=False),
                    opening_hook_urdu=item["hook"],
                    thumbnail_concept_urdu=item["thumbnail"],
                    priority_score=item["score"],
                    rationale_urdu=item["rationale"],
                    uncertainty_notes_urdu=item["uncertainty"],
                    content_fingerprint=fp,
                    status=ProposalStatus.PROPOSED,
                )
                session.add(proposal)
                saved += 1

            await session.commit()

        logger.info(f"{saved} نئے اسلامی تاریخی موضوعات ڈیٹا بیس میں محفوظ ہوئے")
        return saved

    async def get_all_proposals(
        self, category: Optional[ContentCategory] = None
    ) -> List[ContentTopicProposal]:
        """تمام تجاویز واپس کرے"""
        async with AsyncSessionLocal() as session:
            stmt = select(ContentTopicProposal)
            if category:
                stmt = stmt.where(ContentTopicProposal.category == category)
            stmt = stmt.order_by(ContentTopicProposal.priority_score.desc())
            return list((await session.execute(stmt)).scalars().all())


# Singleton
topic_generator = TopicGenerator()
